import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { mkdir, writeFile, readFile } from 'node:fs/promises';

const root = fileURLToPath(new URL('..', import.meta.url));
const require = createRequire(import.meta.url);
let esbuild;
try { esbuild = require('esbuild'); }
catch (error) {
  if (!process.env.GAME_WORKSHOP_BUILD_TOOLS) throw error;
  esbuild = createRequire(resolve(process.env.GAME_WORKSHOP_BUILD_TOOLS, 'package.json'))('esbuild');
}
await mkdir(resolve(root, 'dist'), { recursive: true });
await esbuild.build({
  entryPoints: [resolve(root, 'client/index.js')], outfile: resolve(root, 'dist/client.js'),
  bundle: true, format: 'iife', platform: 'browser', target: ['chrome120', 'firefox120', 'safari17'],
  minify: false, sourcemap: false, legalComments: 'inline', charset: 'utf8',
  banner: { js: '/*! dsh-game-workshop 0.1.0 | Copyright (c) 2026 a348579184 | MIT License */' },
});
const presets = await readFile(resolve(root, 'editors/presets.patch.yml'), 'utf8');
const patch = '# Generated by npm run build. Do not edit; change editors/presets.patch.yml instead.\n- insert:\n    - id: game-workshop\n      name: dsh-game-workshop\n      config: {}\n\n' + presets;
await writeFile(resolve(root, 'cordis.patch.yml'), patch);
console.log('Built dist/client.js and cordis.patch.yml; no install-time scripts are required.');
